from __future__ import annotations

import csv
import math
import statistics
from pathlib import Path

ROOT = Path(r"C:\humanoid_rl_lab\logs\thesis\router")
HOLDOUT_SEEDS = (110, 111, 112, 113, 114)

EXPECTED_SCRIPT_SHA256 = "43E987FC0FF451086D4FE63BD279006195F447484F00699D9220BFF97DD2D3B3"
EXPECTED_ENTER = 0.20
EXPECTED_EXIT = 0.10
EXPECTED_BRAKE_S = 0.36
EXPECTED_BRAKE_STEPS = 18
EXPECTED_TRANSITION_SEQUENCE = [
    ("STAND", "LOCO"),
    ("LOCO", "BRAKE"),
    ("BRAKE", "LOCO"),
    ("LOCO", "BRAKE"),
    ("BRAKE", "STAND"),
]
EXPECTED_CANCELED_BRAKE_LENGTHS = [5]
EXPECTED_COMPLETED_BRAKE_LENGTHS = [18]

PASS_MARKER = "V2G_V4N_ROUTER_HYSTERESIS_HOLDOUT_110_114_OFFLINE_AUDIT_PASS"


def fail(msg: str) -> None:
    raise RuntimeError(msg)


def parse_summary(path: Path) -> dict[str, str]:
    data: dict[str, str] = {}
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or "=" not in line:
            continue
        key, value = line.split("=", 1)
        data[key.strip()] = value.strip()
    return data


def latest_holdout_dir(seed: int) -> Path:
    suffix = f"_v2g_v4n_router_untouched_holdout_seed{seed}"
    matches = sorted(
        (p for p in ROOT.iterdir() if p.is_dir() and p.name.endswith(suffix)),
        key=lambda p: p.name,
    )
    if not matches:
        fail(f"missing holdout directory for seed {seed}")
    return matches[-1]


def num(data: dict[str, str], key: str) -> float:
    if key not in data:
        fail(f"missing numeric key: {key}")
    try:
        value = float(data[key])
    except ValueError:
        fail(f"non-numeric {key}={data[key]!r}")
    if not math.isfinite(value):
        fail(f"non-finite {key}={value}")
    return value


def parse_int_list(text: str) -> list[int]:
    text = text.strip()
    if not (text.startswith("[") and text.endswith("]")):
        fail(f"invalid int-list format: {text}")
    inner = text[1:-1].strip()
    if not inner:
        return []
    return [int(x.strip()) for x in inner.split(",")]


def parse_transition_sequence(text: str) -> list[tuple[str, str]]:
    # Expected summary format is Python repr of list of tuples, generated by frozen harness.
    import ast as _ast
    try:
        value = _ast.literal_eval(text)
    except Exception as exc:
        fail(f"invalid transition_sequence: {text!r}: {exc}")
    if not isinstance(value, list):
        fail(f"transition_sequence is not a list: {value!r}")
    out: list[tuple[str, str]] = []
    for item in value:
        if not (isinstance(item, tuple) and len(item) == 2):
            fail(f"bad transition item: {item!r}")
        out.append((str(item[0]), str(item[1])))
    return out


def mean_sd(values: list[float]) -> tuple[float, float]:
    return (
        statistics.fmean(values),
        statistics.stdev(values) if len(values) > 1 else 0.0,
    )


def main() -> None:
    if not ROOT.is_dir():
        fail(f"router log root missing: {ROOT}")

    rows = []
    input_lines = []

    for seed in HOLDOUT_SEEDS:
        result_dir = latest_holdout_dir(seed)
        summary_path = result_dir / "summary.txt"
        if not summary_path.is_file():
            fail(f"missing summary.txt for seed {seed}: {summary_path}")

        data = parse_summary(summary_path)

        if data.get("seed") != str(seed):
            fail(f"seed mismatch for {seed}: {data.get('seed')}")
        if data.get("script_sha256", "").upper() != EXPECTED_SCRIPT_SHA256:
            fail(
                f"script SHA mismatch seed {seed}: "
                f"{data.get('script_sha256')} != {EXPECTED_SCRIPT_SHA256}"
            )
        if data.get("termination") != "NO":
            fail(f"termination != NO for seed {seed}")
        if data.get("scientific_role") != "UNTOUCHED_HOLDOUT_VALIDATION":
            fail(f"wrong scientific_role for seed {seed}: {data.get('scientific_role')}")
        if data.get("threshold_status") != "FROZEN_DEVELOPMENT_CALIBRATED_BEFORE_HOLDOUT":
            fail(f"threshold status mismatch seed {seed}")
        if data.get("dwell_status") != "FROZEN_ENGINEERING_HANDOFF_PRIMITIVE":
            fail(f"dwell status mismatch seed {seed}")
        if data.get("post_holdout_tuning") != "FORBIDDEN":
            fail(f"post-holdout tuning guardrail missing seed {seed}")
        if data.get("blending") != "ABSENT":
            fail(f"blending unexpectedly present seed {seed}")

        if abs(num(data, "enter_loco_speed") - EXPECTED_ENTER) > 1e-12:
            fail(f"ENTER mismatch seed {seed}")
        if abs(num(data, "exit_loco_speed") - EXPECTED_EXIT) > 1e-12:
            fail(f"EXIT mismatch seed {seed}")
        if abs(num(data, "brake_s") - EXPECTED_BRAKE_S) > 1e-12:
            fail(f"brake_s mismatch seed {seed}")
        if int(round(num(data, "brake_steps"))) != EXPECTED_BRAKE_STEPS:
            fail(f"brake_steps mismatch seed {seed}")

        transitions = parse_transition_sequence(data["transition_sequence"])
        if transitions != EXPECTED_TRANSITION_SEQUENCE:
            fail(
                f"transition sequence mismatch seed {seed}: "
                f"{transitions} != {EXPECTED_TRANSITION_SEQUENCE}"
            )

        canceled = parse_int_list(data["canceled_brake_lengths"])
        completed = parse_int_list(data["completed_brake_lengths"])
        if canceled != EXPECTED_CANCELED_BRAKE_LENGTHS:
            fail(f"canceled BRAKE mismatch seed {seed}: {canceled}")
        if completed != EXPECTED_COMPLETED_BRAKE_LENGTHS:
            fail(f"completed BRAKE mismatch seed {seed}: {completed}")

        row = {
            "seed": seed,
            "result_dir": str(result_dir),
            "final2_mean_vxy_mps": num(data, "final2_mean_vxy_mps"),
            "final2_max_vxy_mps": num(data, "final2_max_vxy_mps"),
            "final2_mean_tilt_deg": num(data, "final2_mean_tilt_deg"),
            "final2_max_tilt_deg": num(data, "final2_max_tilt_deg"),
            "final2_mean_abs_wz_radps": num(data, "final2_mean_abs_wz_radps"),
            "final2_double_support_pct": num(data, "final2_double_support_pct"),
        }
        rows.append(row)
        input_lines.append(
            f"seed {seed}: {result_dir.name} | termination=NO | "
            f"transitions PASS | brake cancel=5 | brake complete=18"
        )

    out_dir = ROOT / "untouched_holdout_110_114_offline_audit"
    out_dir.mkdir(parents=True, exist_ok=True)

    csv_path = out_dir / "holdout_110_114_metrics.csv"
    report_path = out_dir / "holdout_110_114_report.txt"

    with csv_path.open("w", newline="", encoding="utf-8") as fh:
        writer = csv.DictWriter(fh, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)

    metrics = (
        "final2_mean_vxy_mps",
        "final2_max_vxy_mps",
        "final2_mean_tilt_deg",
        "final2_max_tilt_deg",
        "final2_mean_abs_wz_radps",
        "final2_double_support_pct",
    )

    aggregates = {}
    for key in metrics:
        vals = [float(r[key]) for r in rows]
        mean, sd = mean_sd(vals)
        aggregates[key] = {
            "mean": mean,
            "sd": sd,
            "min": min(vals),
            "max": max(vals),
        }

    report = []
    report.append("=" * 136)
    report.append("v2-G / v4-N ROUTER + HYSTERESIS TRUE UNTOUCHED HOLDOUT AUDIT")
    report.append("=" * 136)
    report.append("holdout seeds             : 110,111,112,113,114")
    report.append("development seeds         : 100-109 excluded before holdout")
    report.append("EXIT threshold            : 0.10 m/s [FROZEN]")
    report.append("ENTER threshold           : 0.20 m/s [FROZEN]")
    report.append("braking dwell             : 0.36 s / 18 steps [FROZEN]")
    report.append("blending                  : ABSENT")
    report.append("post-holdout tuning       : FORBIDDEN")
    report.append("simulator execution       : ABSENT (offline summary audit)")
    report.append("")
    report.append("[INPUT VALIDATION]")
    report.extend(input_lines)
    report.append("")
    report.append("[FINAL 2 s AGGREGATES ACROSS HOLDOUT SEEDS]")
    for key in metrics:
        a = aggregates[key]
        report.append(
            f"{key:<35} "
            f"mean={a['mean']:.9f}  sd={a['sd']:.9f}  "
            f"min={a['min']:.9f}  max={a['max']:.9f}"
        )
    report.append("")
    report.append("[ROUTER INVARIANTS]")
    report.append("transition sequence exact                 : 5/5")
    report.append("canceled BRAKE length = 5 steps          : 5/5")
    report.append("completed BRAKE length = 18 steps        : 5/5")
    report.append("termination = NO                          : 5/5")
    report.append("frozen EXIT/ENTER/dwell provenance        : 5/5")
    report.append("blending absent                            : 5/5")
    report.append("")
    report.append("[INTERPRETATION]")
    report.append(
        "This audit summarizes the preregistered untouched holdout set only. "
        "No additional seed is added, removed, or reclassified based on outcome."
    )
    report.append(
        "A PASS establishes that the frozen router/hysteresis/handoff configuration "
        "completed the full validation schedule on all five untouched holdout seeds "
        "with exact routing invariants and without termination."
    )
    report.append(PASS_MARKER)

    report_path.write_text("\n".join(report) + "\n", encoding="utf-8")

    print("\n".join(report), flush=True)
    print(f"\nmetrics CSV              : {csv_path}")
    print(f"report                   : {report_path}")


if __name__ == "__main__":
    main()
